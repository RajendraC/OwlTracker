"""Writes app/src/main/assets/scenes/bright-art.js (the pre-drawn glossy pieces of the bright pictures) and
bright-font.js (the two weights of the app's font the pictures use, from app/src/main/res/font, so the page needs
no font file and fetches nothing).
python3 tools/scenes/export_bright.py"""
import base64
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bright  # noqa: E402

APP = os.path.join(HERE, "..", "..", "app", "src", "main")
OUT = os.path.join(APP, "assets", "scenes", "bright-art.js")
FONT_OUT = os.path.join(APP, "assets", "scenes", "bright-font.js")
FONTS = (("600", "jakarta_semibold.ttf"), ("800", "jakarta_extrabold.ttf"))

if __name__ == "__main__":
    art = {name: [defs, body] for name, (defs, body) in bright.ART.items()}
    text = ("/* Generated by tools/scenes/export_bright.py from art5.py and art6.py: the glossy pieces of the bright pictures. */\n"
            "window.BRIGHT_ART = " + json.dumps(art, ensure_ascii=False, separators=(",", ":")) + ";\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT), len(text), "bytes,", len(art), "pieces")

    faces = []
    for weight, name in FONTS:
        with open(os.path.join(APP, "res", "font", name), "rb") as f:
            faces.append([weight, base64.b64encode(f.read()).decode("ascii")])
    text = ("/* Generated by tools/scenes/export_bright.py: Plus Jakarta Sans 600 and 800 (subset), the app's font, for the\n"
            "   pictures' text. SIL Open Font License 1.1: see ../fonts/OFL.txt. */\n"
            "window.BRIGHT_FONTS = " + json.dumps(faces, separators=(",", ":")) + ";\n")
    with open(FONT_OUT, "w", encoding="ascii") as f:
        f.write(text)
    print("wrote", os.path.relpath(FONT_OUT), len(text), "bytes")
